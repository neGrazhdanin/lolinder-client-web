import { readFileSync, writeFileSync } from 'node:fs';
import { palette, SEED } from './tokens.mjs';

const CSS = new URL('../../src/styles/main.css', import.meta.url);
const START = '/* palette:start';
const END = '/* palette:end */';

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const rule = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n')}\n}\n`;
const prefixed = (prefix, values) =>
  Object.fromEntries(
    Object.entries(values).map(([name, value]) => [`${prefix}${kebab(name)}`, value]),
  );

const { scheme, results, tiers } = palette();
const resultVars = (theme) =>
  Object.fromEntries(
    Object.entries(results).flatMap(([name, value]) => [
      [name, value[theme].color],
      [`${name}-muted`, value[theme].muted],
    ]),
  );

const block = [
  `${START}: generated by \`pnpm palette\` from seed ${SEED} (Material 3 SchemeTonalSpot). Do not edit by hand. */`,
  rule(':root', { ...prefixed('md-', scheme.light), ...resultVars('light') }),
  rule('.dark', { ...prefixed('md-', scheme.dark), ...resultVars('dark') }),
  ...Object.entries(tiers).flatMap(([name, value]) => [
    rule(`[data-tier='${name}']`, prefixed('tier-', value.light)),
    rule(`.dark [data-tier='${name}']`, prefixed('tier-', value.dark)),
  ]),
  END,
].join('\n');

const css = readFileSync(CSS, 'utf8');
const start = css.indexOf(START);
const end = css.indexOf(END);
if (start < 0 || end < start) throw new Error('palette markers not found in main.css');
writeFileSync(CSS, css.slice(0, start) + block + css.slice(end + END.length));
